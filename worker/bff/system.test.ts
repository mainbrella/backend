import test from 'node:test';
import assert from 'node:assert/strict';
import { LIMITS } from './contracts';
import { workerCode } from './runtime';
import { runtime } from './system-test-helpers';

test('runtime code enforces explicit resource limits without inherited bindings', () => {
  const code = workerCode('export default () => 1');
  assert.equal(code.globalOutbound, null);
  assert.deepEqual(code.env, {});
  assert.deepEqual(code.limits, { cpuMs: LIMITS.cpuMs, subRequests: LIMITS.databaseCalls + 1 });
  assert.equal(code.compatibilityFlags, undefined);
});

test('real Workers runtime: project lifecycle, transactional migrations, and isolated JavaScript', { timeout: 60_000 }, async t => {
  const f = await runtime(t);
  assert.deepEqual((await f.json('/projects')).projects, []);
  assert.equal((await f.request('/projects', 'GET', undefined, 'no-session')).status, 401);
  assert.equal((await f.request('/projects', 'POST', { name: 'forbidden', template: 'empty' }, 'owner', { origin: 'https://evil.example' })).status, 403);
  const { project } = await f.json('/projects', 'POST', { name: 'My backend', template: 'empty' }, 201);
  const base = `/projects/${project.id}`;
  assert.equal((await f.json('/projects', 'POST', { name: 'My backend', template: 'empty' })).project.id, project.id);
  assert.equal(f.databases.size, 0, 'Creation does not implicitly seed or provision data');
  assert.equal((await f.request(base, 'GET', undefined, 'stranger')).status, 404);
  assert.equal((await f.request(`${base}/provision`, 'POST', undefined, 'stranger')).status, 404);

  f.loseCreateResponse();
  await f.json(`${base}/provision`, 'POST', undefined, 502);
  assert.equal((await f.json(base)).project.state, 'error');
  assert.equal((await f.json(`${base}/provision`, 'POST')).project.state, 'ready');
  assert.equal(f.databases.size, 1, 'Retry recovers the database created before a lost response');
  assert.deepEqual((await f.json(`${base}/schema`)).tables, []);
  assert.deepEqual((await f.json(`${base}/migrations`)).migrations, []);
  assert.deepEqual((await f.json(`${base}/functions`)).functions, []);
  assert.deepEqual((await f.json(`${base}/executions`)).executions, []);

  const first = { sequence: 1, name: 'create_notes', sql: 'CREATE TABLE notes(id TEXT PRIMARY KEY, body TEXT NOT NULL); CREATE INDEX notes_body ON notes(body);' };
  assert.equal((await f.json(`${base}/migrations`, 'POST', first)).applied, true);
  assert.equal((await f.json(`${base}/migrations`, 'POST', first)).applied, false);
  await f.json(`${base}/migrations`, 'POST', { ...first, sql: first.sql + ' SELECT 1;' }, 409);
  await f.json(`${base}/migrations`, 'POST', { sequence: 3, name: 'out_of_order', sql: 'CREATE TABLE should_not_exist(id TEXT)' }, 409);
  await f.json(`${base}/migrations`, 'POST', { sequence: 2, name: 'broken', sql: 'CREATE TABLE rolled_back(id TEXT); INSERT INTO absent_table VALUES(1);' }, 502);
  assert.equal((await f.json(`${base}/migrations`)).migrations.length, 1);
  assert.deepEqual((await f.json(`${base}/schema`)).tables.map((item: any) => [item.name, item.count]), [['notes', 0]]);
  for (const sql of ['PRAGMA writable_schema=ON', 'SELECT * FROM _bff_migrations', 'CREATE TABLE outside_migration(id TEXT)', 'SELECT 1; SELECT 2']) await f.json(`${base}/query`, 'POST', { sql }, 400);
  await f.json(`${base}/query`, 'POST', { sql: 'INSERT INTO notes VALUES(?,?)', params: ['one', 'Hello; still one row'] });
  assert.equal((await f.json(`${base}/schema`)).tables[0].count, 1);
  assert.equal((await f.json(`${base}/query`, 'POST', { sql: 'SELECT * FROM notes' })).result.results[0].body, 'Hello; still one row');

  const fnPath = `${base}/functions/read_notes`;
  const readSource = `export default async (input, ctx) => (await ctx.db.select('notes', {id:input.id})).results`;
  await f.json(fnPath, 'PUT', { source: readSource, expectedVersion: 0, databaseAccess: 'read' }, 201);
  await f.json(fnPath, 'PUT', { source: readSource, expectedVersion: 0, databaseAccess: 'write' }, 409);
  const invoked = await f.json(`${fnPath}/invoke`, 'POST', { input: { id: 'one' } });
  assert.equal(invoked.ok, true); assert.equal(invoked.value[0].body, 'Hello; still one row');
  const invoke = async (name: string, source: string, databaseAccess = 'none') => {
    await f.json(`${base}/functions/${name}`, 'PUT', { source, expectedVersion: 0, databaseAccess }, 201);
    return f.json(`${base}/functions/${name}/invoke`, 'POST', { input: null });
  };
  const egress = await invoke('network', `import {env} from 'cloudflare:workers'; import {connect} from 'cloudflare:sockets'; export default async () => { let denied=false,tcpDenied=false; try {await fetch('https://evil.example')} catch {denied=true} try {await connect({hostname:'evil.example',port:80}).opened} catch {tcpDenied=true} return {denied,tcpDenied,keys:Object.keys(env)}; }`);
  assert.deepEqual(egress.value, { denied: true, tcpDenied: true, keys: [] });
  const readOnly = await invoke('read_only', `export default async (_,ctx) => ctx.db.insert('notes',{id:'bad',body:'bad'})`, 'read');
  assert.equal(readOnly.ok, false); assert.match(readOnly.error, /database_write_denied/);
  assert.equal((await invoke('metadata', `export default async (_,ctx) => ctx.db.select('_bff_migrations')`, 'read')).ok, false);
  assert.equal((await invoke('injection', `export default async (_,ctx) => ctx.db.select('notes;DROP TABLE notes')`, 'read')).ok, false);
  const quota = await invoke('call_limit', `export default async (_,ctx) => {for(let i=0;i<11;i++) await ctx.db.select('notes');}`, 'read');
  assert.equal(quota.ok, false); assert.match(quota.error, /database_call_limit/);
  assert.equal((await invoke('write_notes', `export default async (_,ctx) => (await ctx.db.insert('notes',{id:'two',body:'Created in isolate'})).results`, 'write')).ok, true);
  const stateSource = `let n=0; export default () => ++n`;
  assert.equal((await invoke('fresh_state', stateSource)).value, 1);
  assert.equal((await f.json(`${base}/functions/fresh_state/invoke`, 'POST', { input: null })).value, 1);
  const noDb = await invoke('no_db', `export default (_,ctx) => ctx.db`);
  assert.equal(noDb.value, null);
  await f.json(`${base}/functions/huge`, 'PUT', { source: `export default () => 'x'.repeat(70000)`, expectedVersion: 0 }, 201);
  await f.json(`${base}/functions/huge/invoke`, 'POST', { input: null }, 413);
  await f.json(`${base}/functions/broken_js`, 'PUT', { source: 'export default !!!', expectedVersion: 0 }, 201);
  await f.json(`${base}/functions/broken_js/invoke`, 'POST', { input: null }, 422);
  await f.json(`${base}/functions/sleep_forever`, 'PUT', { source: 'export default async () => {await new Promise(resolve => setTimeout(resolve,10000));return 1}', expectedVersion: 0 }, 201);
  await f.json(`${base}/functions/sleep_forever/invoke`, 'POST', { input: null }, 408);

  const other = (await f.json('/projects', 'POST', { name: 'Second backend', template: 'empty' }, 201)).project;
  await f.json(`/projects/${other.id}/provision`, 'POST');
  assert.equal(f.databases.size, 2);
  assert.deepEqual((await f.json(`/projects/${other.id}/schema`)).tables, []);
  const parallel = await Promise.all([1, 2].map(() => f.request('/projects', 'POST', { name: 'Parallel', template: 'empty' }).then(async response => {
    assert.ok(response.status === 200 || response.status === 201); return response.json() as Promise<any>;
  })));
  assert.equal(parallel[0].project.id, parallel[1].project.id);
  const nextMigration = { sequence: 2, name: 'add_title', sql: 'ALTER TABLE notes ADD COLUMN title TEXT;' };
  const applied = await Promise.all([f.json(`${base}/migrations`, 'POST', nextMigration), f.json(`${base}/migrations`, 'POST', nextMigration)]);
  assert.deepEqual(applied.map(value => value.applied).sort(), [false, true]);
  assert.equal((await f.request(fnPath, 'PUT', { source: stateSource, expectedVersion: 1 }, 'stranger')).status, 404);
  await f.json(base, 'PATCH', { suspended: true });
  await f.json(`${fnPath}/invoke`, 'POST', { input: null }, 403);
  await f.json(`${base}/query`, 'POST', { sql: 'SELECT * FROM notes' }, 403);
  assert.ok((await f.json(`${base}/executions`)).executions.some((item: any) => item.status === 'error'));
  await f.json(base, 'PATCH', { suspended: false });
  const ledger = (await f.json(`${base}/migrations`)).migrations;
  assert.equal(ledger.length, 2);
  assert.equal(ledger[1].sql, first.sql);
  const logs = (await f.json(`${base}/executions`)).executions;
  assert.ok(logs.every((entry: any) => !('input' in entry) && !('result' in entry)));
  for (let i = 0; i < 3; i++) await f.db.prepare(`INSERT INTO bff_executions(id,project_id,function_name,version,status,expires_at,created_at)
    VALUES(?,?,'read_notes',1,'running',?,?)`).bind(crypto.randomUUID(), project.id, Date.now() + 60_000, new Date().toISOString()).run();
  await f.json(`${fnPath}/invoke`, 'POST', { input: null }, 429);
  await f.db.prepare("DELETE FROM bff_executions WHERE status='running'").run();
  f.redirectNextQuery();
  await f.json(`${base}/query`, 'POST', { sql: 'SELECT 1' }, 502);
  assert.ok(f.outboundTargets.every(origin => origin === 'https://api.cloudflare.com'), 'Neither customer egress nor provider redirects may reach another host');
  await f.json('/projects', 'POST', { name: 'Fourth', template: 'empty' }, 201);
  await f.json('/projects', 'POST', { name: 'Fifth', template: 'empty' }, 201);
  await f.json('/projects', 'POST', { name: 'Sixth', template: 'empty' }, 429);
  const today = new Date().toISOString().slice(0, 10);
  await f.db.prepare('UPDATE bff_daily_usage SET invocations=? WHERE project_id=? AND day=?').bind(LIMITS.invocationsPerDay, project.id, today).run();
  await f.json(`${fnPath}/invoke`, 'POST', { input: null }, 429);
  assert.ok((await f.json(`${base}/usage`)).queries > 0);
  await f.db.prepare('UPDATE bff_daily_usage SET queries=? WHERE project_id=? AND day=?').bind(LIMITS.queriesPerDay, project.id, today).run();
  await f.json(`${base}/query`, 'POST', { sql: 'SELECT 1' }, 429);
  await f.db.prepare('UPDATE bff_projects SET blocked=1 WHERE id=?').bind(project.id).run();
  await f.json(base, 'PATCH', { suspended: false }, 403);
  await f.json(`${base}/query`, 'POST', { sql: 'SELECT 1' }, 403);
  await f.db.prepare("DELETE FROM users WHERE id='owner'").run();
  assert.equal((await f.db.prepare('SELECT COUNT(*) AS n FROM bff_database_deletions').first())!.n, 5);
  await f.db.prepare("UPDATE bff_database_deletions SET created_at='2020-01-01'").run();
  f.failNextDelete();
  await f.mf.dispatchFetch('https://internal/__test_cleanup');
  assert.equal(f.databases.size, 1, 'A failed remote deletion stays queued for retry');
  await f.mf.dispatchFetch('https://internal/__test_cleanup');
  assert.equal(f.databases.size, 0);
  assert.equal((await f.db.prepare('SELECT COUNT(*) AS n FROM bff_database_deletions').first())!.n, 0);
});
